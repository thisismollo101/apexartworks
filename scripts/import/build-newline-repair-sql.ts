/**
 * Repair the clips whose prompt arrived with its line breaks escaped.
 *
 * 44 rows in the sheet stored their newlines as the two characters
 * backslash-n (and their quotes as backslash-quote) and were never unescaped,
 * so each prompt is one unbroken line. pipeline/source.ts now restores them at
 * read time. This regenerates what was derived from the broken text.
 *
 * 21 of the 44 are in the live library, and they are NOT treated alike:
 *
 *   9 clips loaded by the offline library load — ours end to end, so the
 *     prompt, title, summary and the whole shot list are regenerated.
 *
 *   12 clips from the original 766 — their shots and headline were written by
 *     a model. Only verbatim_prompt is corrected; their shots are left exactly
 *     as they are. Re-splitting them would replace model-written prose with
 *     derived text, which is a downgrade, not a repair.
 *
 * Usage: npx tsx scripts/import/build-newline-repair-sql.ts
 */
import fs from 'node:fs';
import path from 'node:path';
import { loadSourceLibrary } from '../../pipeline/source';
import { offlineDecompose } from '../../pipeline/offline-decompose';
import { deriveHeadline } from '../../pipeline/offline-headline';
import { OUT } from './classify';

/** Live clips whose prompt was escaped, split by who authored their shots. */
const MINE = ['3167', '3180', '3181', '3606', '3608', '4032', '4063', '5015', '5532'];
const MODEL_SHOTS = ['3210', '3281', '3376', '3527', '3603', '3605', '4034', '4035', '4592', '4593', '4595', '5026'];

const q = (v: string | number | null): string => {
  if (v === null || v === '') return 'null';
  if (typeof v === 'number') return Number.isFinite(v) ? String(v) : 'null';
  return `'${String(v).replace(/'/g, "''")}'`;
};
const qTag = (v: string) => (v === 'none' || !v ? 'null' : q(v));

function main() {
  const rows = new Map(loadSourceLibrary().map((r) => [r.video_id, r]));
  const parts: string[] = [
    '-- Generated by scripts/import/build-newline-repair-sql.ts — do not hand-edit.',
    '-- Restores escaped line breaks, and re-derives only what we authored.',
    '',
  ];

  // ---- prompt text: corrected for every affected clip ---------------------
  for (const id of [...MINE, ...MODEL_SHOTS]) {
    const r = rows.get(id);
    if (!r) continue;
    parts.push(
      `update clips set verbatim_prompt = ${q(r.verbatim_prompt)} where clip_id = ${q(`APX-C-${id}`)};`,
    );
  }
  parts.push('');

  // ---- ours: headline + shot list regenerated from the restored text ------
  for (const id of MINE) {
    const r = rows.get(id);
    if (!r) continue;
    const { title, summary } = deriveHeadline(r.verbatim_prompt);
    const d = offlineDecompose({ title, summary, verbatim_prompt: r.verbatim_prompt });
    if (d.shots.length === 0) continue;
    const clipId = `APX-C-${id}`;

    parts.push(
      `update clips set title = ${q(title)}, summary = ${q(summary)}, ` +
        `runtime_s = ${d.runtime_s === null ? 'null' : d.runtime_s}, ` +
        `aspect_ratio = ${q(d.aspect_ratio)}, shot_count = ${d.shots.length}, ` +
        `realism_level = ${q(d.realism_level)}, grade = ${q(d.grade)}, ` +
        `motion_feel = ${q(d.motion_feel)} where clip_id = ${q(clipId)};`,
    );
    // Replace wholesale: the old split came from the unbroken text, so its
    // shot boundaries are wrong, not merely fewer.
    parts.push(`delete from shots where clip_id = ${q(clipId)};`);

    const values = d.shots.map((s) => {
      const dur = s.tc_in >= 0 && s.tc_out >= 0 ? Math.round((s.tc_out - s.tc_in) * 10) / 10 : null;
      return `(${[
        q(`APX-S-${id}-${s.shot_index}`), q(clipId), String(s.shot_index),
        s.tc_in >= 0 ? String(s.tc_in) : 'null',
        s.tc_out >= 0 ? String(s.tc_out) : 'null',
        dur === null ? 'null' : String(dur),
        q(s.verbatim_text), q(s.description),
        qTag(s.subject_role), qTag(s.action), qTag(s.food_item),
        qTag(s.food_role), qTag(s.setting), qTag(s.mood),
      ].join(', ')})`;
    });
    parts.push(
      `insert into shots (shot_id, clip_id, shot_index, tc_in, tc_out, duration_s,\n` +
        `  verbatim_text, description, subject_role, action, food_item, food_role, setting, mood) values\n` +
        `${values.join(',\n')}\non conflict (shot_id) do nothing;`,
      '',
    );
  }

  fs.mkdirSync(OUT, { recursive: true });
  const out = path.join(OUT, 'newline_repair.sql');
  const sql = `${parts.join('\n')}\n`;
  fs.writeFileSync(out, sql, 'utf8');
  console.log(`Wrote ${out} — ${MINE.length} re-split, ${MODEL_SHOTS.length} prompt-only (${Math.round(sql.length / 1024)} KB)`);
}

main();
